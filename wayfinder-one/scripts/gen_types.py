#!/usr/bin/env python3
"""Generate contracts/types.ts from contracts/models.py (run from repo root: python scripts/gen_types.py).
Owner: P3. Never hand-edit types.ts. CI fails if the committed file differs from the generated one."""
import inspect
import sys
import typing
from pathlib import Path

from pydantic import BaseModel

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from contracts import models as m


def lit(v) -> str:
    if isinstance(v, bool):
        return str(v).lower()
    return f'"{v}"' if isinstance(v, str) else str(v)


def ts_type(s: dict) -> str:
    if "$ref" in s:
        return s["$ref"].split("/")[-1]
    if "enum" in s:
        return " | ".join(lit(v) for v in s["enum"])
    if "const" in s:
        return lit(s["const"])
    if "anyOf" in s:
        return " | ".join(dict.fromkeys(ts_type(x) for x in s["anyOf"]))
    t = s.get("type")
    if t == "string":
        return "string"
    if t in ("integer", "number"):
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "null":
        return "null"
    if t == "array":
        inner = ts_type(s.get("items", {}))
        return f"({inner})[]" if " | " in inner else f"{inner}[]"
    if t == "object":
        ap = s.get("additionalProperties")
        if isinstance(ap, dict) and ap:
            return f"Record<string, {ts_type(ap)}>"
        return "Record<string, unknown>"
    return "unknown"


def main() -> None:
    out = [
        "// AUTO-GENERATED by scripts/gen_types.py from contracts/models.py. DO NOT EDIT.",
        f'export const CONTRACT_VERSION = "{m.CONTRACT_VERSION}";',
        "",
    ]
    for name, val in vars(m).items():
        if name[:1].isupper() and typing.get_origin(val) is typing.Literal:
            out.append(f"export type {name} = " + " | ".join(lit(a) for a in typing.get_args(val)) + ";")
    out.append("")
    models = [c for _, c in inspect.getmembers(m, inspect.isclass)
              if issubclass(c, BaseModel) and c is not BaseModel and c.__module__ == m.__name__]
    for cls in sorted(models, key=lambda c: c.__name__):
        schema = cls.model_json_schema(mode="serialization")
        out.append(f"export interface {cls.__name__} {{")
        for pname, ps in schema.get("properties", {}).items():
            out.append(f"  {pname}: {ts_type(ps)};")  # defaults are always present in API output
        out.append("}")
        out.append("")
    (ROOT / "contracts" / "types.ts").write_text("\n".join(out))
    print(f"wrote contracts/types.ts ({len(models)} interfaces)")


if __name__ == "__main__":
    main()
